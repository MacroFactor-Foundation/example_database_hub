# Markdown data dictionary rendered from config/schema.yml and the vocabulary
# file. Used for data/README.md and for the site's data page.
render_data_dictionary <- function(schema, vocabulary, heading_level = 2) {
  h <- function(level, text) paste(strrep("#", level), text)
  allowed <- function(spec) {
    v <- spec[["vocab"]] %||% spec[["vocab_list"]]
    if (is.null(v)) {
      bounds <- c(if (!is.null(spec$min)) paste("≥", spec$min), if (!is.null(spec$max)) paste("≤", spec$max))
      if (!is.null(spec$pattern)) bounds <- c(bounds, paste0("pattern `", spec$pattern, "`"))
      return(paste(bounds, collapse = ", "))
    }
    vals <- vocabulary$value[vocabulary$vocabulary == v]
    prefix <- if (!is.null(spec[["vocab_list"]])) "comma-separated list of " else ""
    if (length(vals) <= 6) paste0(prefix, paste0("`", vals, "`", collapse = ", ")) else paste0(prefix, "vocabulary `", v, "`")
  }
  out <- character()
  for (name in names(schema$tables)) {
    t <- schema$tables[[name]]
    fk <- vapply(t$foreign_keys, function(k) paste0("(", paste(k$columns, collapse = ", "), ") → `", k$references, "` (", paste(k$ref_columns, collapse = ", "), ")"), character(1))
    cols <- data.frame(
      Column = paste0("`", names(t$columns), "`"),
      Type = vapply(t$columns, function(c) c$type, character(1)),
      Required = vapply(t$columns, function(c) if (isTRUE(c$required)) "yes" else "", character(1)),
      Allowed = vapply(t$columns, allowed, character(1)),
      Description = vapply(t$columns, function(c) c$description %||% "", character(1)),
      check.names = FALSE
    )
    out <- c(
      out,
      h(heading_level, paste0("`", name, "`")), "",
      t$description, "",
      paste0("- **File:** `", t$file, "`"),
      paste0("- **One row per:** ", t$grain),
      paste0("- **Primary key:** (", paste(t$primary_key, collapse = ", "), ")"),
      if (length(fk)) paste0("- **Foreign keys:** ", paste(fk, collapse = "; ")),
      "", md_table(cols), ""
    )
  }
  vocab_names <- unique(vocabulary$vocabulary)
  out <- c(out, h(heading_level, "Controlled vocabularies"), "",
    paste0("Defined in `", schema$vocabulary_file, "`. Values are case-sensitive."), "")
  for (v in vocab_names) {
    rows <- vocabulary[vocabulary$vocabulary == v, ]
    desc <- ifelse(is.na(rows$description), "", rows$description)
    out <- c(out, h(heading_level + 1, paste0("`", v, "`")), "",
      md_table(data.frame(Value = paste0("`", rows$value, "`"), Description = desc)), "")
  }
  out
}

# Full text of data/README.md (regenerate with scripts/build_data_dictionary.R).
build_data_readme <- function(schema, vocabulary) {
  unname(c(
    "<!-- Generated from config/schema.yml by scripts/build_data_dictionary.R. Do not edit by hand. -->",
    "",
    "# Data dictionary",
    "",
    "> **These tables contain synthetic toy data.** They reproduce the structure of a real",
    "> resistance-training extraction corpus, but every study, author, DOI and value is invented",
    "> (see `data-raw/generate_toy_data.R`). Do not use them for inference.",
    "",
    "One CSV per normalized entity, joined by stable identifiers that are assigned once and never",
    "reused or renumbered. Files are UTF-8, comma-separated, LF line endings, with an empty field",
    "meaning *missing* (the literal text `NA` is a value, and will fail vocabulary checks).",
    "",
    "Every rule below is enforced by `R/validate.R` on each pull request",
    "(`.github/workflows/validate-data.yml`). To add or change a column, edit",
    "`config/schema.yml`, regenerate this file, and update the affected CSVs in the same pull request.",
    "",
    "## How the tables relate",
    "",
    "- `study` has many `arm`s and many `measure`s.",
    "- `arm` has many `arm_week`s (its timeline); each `arm_week` has many `training_set`s.",
    "- `outcome` and `contrast` rows each reference an arm-week *and* a measure, which must belong",
    "  to the same study.",
    "- `reliability` rows reference a `measure`.",
    "",
    render_data_dictionary(schema, vocabulary, heading_level = 2)
  ))
}

write_data_dictionary <- function(schema, vocabulary, path) {
  write_md(render_data_dictionary(schema, vocabulary, heading_level = 2), path)
}
